LOG_LINE_RE = re.compile(r"^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2} (DEBUG|INFO|WARNING|ERROR|CRITICAL) ")
WARNING_RE = re.compile(r"^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2} WARNING (\S+:\d+: [A-Z_]+)(?: \|.*)?$")


# ---------------------------------------------------------------- helpers

def load_module(name):
    return importlib.import_module(name)


def run_cli(args, cwd):
    """Run flight_parser.py as a separate process."""
    return subprocess.run(
        [sys.executable, str(ROOT / "flight_parser.py"), *[str(a) for a in args]],
        cwd=str(cwd), capture_output=True, text=True, timeout=TIMEOUT,
    )


def read_json(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def expected_lines(name):
    return (EXPECTED / name).read_text(encoding="utf-8").splitlines()


def graded_log(path):
    """The graded part of every WARNING line in a log file."""
    out = []
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        m = WARNING_RE.match(line)
        if m:
            out.append(m.group(1))
    return out


def graded_message(message):
    """The graded part of a message returned by parse_files()."""
    return message.split(" | ", 1)[0].rstrip(" |")


def ids(entries):
    return [r["flight_id"] for r in entries]


class TempDirTest(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp(prefix="flightlab_"))

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def assertCleanExit(self, proc, code):
        self.assertNotIn("Traceback", proc.stderr, "the program crashed with a traceback:\n" + proc.stderr)
        self.assertEqual(proc.returncode, code,
                         f"expected exit code {code}, got {proc.returncode}\nstderr:\n{proc.stderr}")


# ---------------------------------------------------------------- A. Structure

class A_Structure(unittest.TestCase):
    FILES = ["flight_parser.py", "validator.py", "csv_loader.py", "query.py", "AI_USAGE.md"]

    def test_required_files_exist(self):
        for name in self.FILES:
            with self.subTest(file=name):
                self.assertTrue((ROOT / name).is_file(), f"{name} is missing from the project root")

    def test_ai_usage_not_empty(self):
        path = ROOT / "AI_USAGE.md"
        self.assertTrue(path.is_file() and path.read_text(encoding="utf-8").strip(),
                        "AI_USAGE.md is missing or empty")

    def test_imports_are_silent(self):
        proc = subprocess.run(
            [sys.executable, "-c", "import flight_parser, validator, csv_loader, query"],
            cwd=str(ROOT), capture_output=True, text=True, timeout=TIMEOUT)
        self.assertEqual(proc.returncode, 0, "importing your modules failed:\n" + proc.stderr)
        self.assertEqual(proc.stdout + proc.stderr, "", "importing your modules must not print anything")

    def test_required_functions_exist(self):
        required = {
            "flight_parser": ["main"],
            "validator": ["load_airports", "validate_row", "to_record"],
            "csv_loader": ["parse_files"],
            "query": ["run_query", "run_queries"],
        }
        for module, funcs in required.items():
            mod = load_module(module)
            for func in funcs:
                with self.subTest(function=f"{module}.{func}"):
                    self.assertTrue(callable(getattr(mod, func, None)), f"{module}.{func} is missing")

    def test_student_constants(self):
        fp = load_module("flight_parser")
        placeholders = {"STUDENT_ID": "000RDB000", "FIRST_NAME": "Firstname", "LAST_NAME": "Lastname"}
        for name, placeholder in placeholders.items():
            with self.subTest(constant=name):
                value = getattr(fp, name, None)
                self.assertIsInstance(value, str, f"{name} must be a string")
                self.assertTrue(value and value.isascii(), f"{name} must be non-empty plain ASCII")
                self.assertNotRegex(value, r"[\s_]", f"{name} must not contain spaces or underscores")
                self.assertNotEqual(value, placeholder, f"set {name} to your own details")

    def test_standard_library_only(self):
        local = {p.stem for p in ROOT.glob("*.py")} | {p.name for p in ROOT.iterdir() if (p / "__init__.py").is_file()}
        allowed = set(sys.stdlib_module_names) | local
        for path in ROOT.glob("*.py"):
            tree = ast.parse(path.read_text(encoding="utf-8"))
            for node in ast.walk(tree):
                names = []
                if isinstance(node, ast.Import):
                    names = [a.name for a in node.names]
                elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
                    names = [node.module]
                for n in names:
                    with self.subTest(file=path.name, module=n):
                        self.assertIn(n.split(".")[0], allowed, f"{path.name} imports non-standard module {n}")


# ---------------------------------------------------------------- B. Row validation

GOOD = ["BA2490", "LHR", "JFK", "2025-11-14 10:30", "2025-11-14 13:05", "489.99"]


def row(**changes):
    keys = ["flight_id", "origin", "destination", "dep", "arr", "price"]
    fields = list(GOOD)
    for k, v in changes.items():
        fields[keys.index(k)] = v
    return fields


class B_RowValidation(TempDirTest):
    CASES = [
        ("valid row", GOOD, None),
        ("whitespace around fields is stripped", [" BA2490 ", " LHR", "JFK ", " 2025-11-14 10:30", "2025-11-14 13:05 ", " 489.99 "], None),
        ("integer price", row(price="120"), None),
        ("too few fields", GOOD[:5], "WRONG_FIELD_COUNT"),
        ("too many fields", GOOD + ["extra"], "WRONG_FIELD_COUNT"),
        ("empty destination", row(destination=""), "MISSING_FIELD"),
        ("whitespace-only price", row(price="   "), "MISSING_FIELD"),
        ("underscore in flight id", row(flight_id="BA_BAD"), "INVALID_FLIGHT_ID"),
        ("flight id too long", row(flight_id="LH9999999"), "INVALID_FLIGHT_ID"),
        ("flight id too short", row(flight_id="B"), "INVALID_FLIGHT_ID"),
        ("non-ASCII flight id", row(flight_id="ĀB12"), "INVALID_FLIGHT_ID"),
        ("origin not in airport list", row(origin="XXX"), "INVALID_ORIGIN"),
        ("lowercase origin", row(origin="lhr"), "INVALID_ORIGIN"),
        ("destination not in airport list", row(destination="LON"), "INVALID_DESTINATION"),
        ("same origin and destination", row(destination="LHR"), "SAME_ORIGIN_DESTINATION"),
        ("departure not zero-padded", row(dep="2025-11-4 9:30"), "INVALID_DEPARTURE"),
        ("departure on a day that does not exist", row(dep="2025-02-30 10:00"), "INVALID_DEPARTURE"),
        ("departure with T separator", row(dep="2025-11-14T10:30"), "INVALID_DEPARTURE"),
        ("arrival hour 24", row(arr="2025-11-14 24:00"), "INVALID_ARRIVAL"),
        ("arrival equal to departure", row(arr="2025-11-14 10:30"), "ARRIVAL_NOT_AFTER_DEPARTURE"),
        ("arrival before departure", row(arr="2025-11-13 23:59"), "ARRIVAL_NOT_AFTER_DEPARTURE"),
        ("price is text", row(price="abc"), "INVALID_PRICE"),
        ("price is nan", row(price="nan"), "INVALID_PRICE"),
        ("price is zero", row(price="0"), "NON_POSITIVE_PRICE"),
        ("price is negative", row(price="-0.01"), "NON_POSITIVE_PRICE"),
        ("check order: flight id before destination and arrival",
         ["BA_BAD", "RIX", "LON", "2025-11-15 11:00", "INVALID_DATE", "250.00"], "INVALID_FLIGHT_ID"),
        ("check order: origin before dates and price", ["XX1", "XXX", "RIX", "bad", "bad", "-1"], "INVALID_ORIGIN"),
        ("check order: departure before arrival", row(dep="bad", arr="bad"), "INVALID_DEPARTURE"),
    ]

    def test_validate_row(self):
        validate_row = load_module("validator").validate_row
        for name, fields, expected in self.CASES:
            with self.subTest(case=name, fields=fields):
                self.assertEqual(validate_row(list(fields), AIRPORT_SET), expected)

    def test_to_record(self):
        to_record = load_module("validator").to_record
        record = to_record([" BA2490", "LHR ", "JFK", "2025-11-14 10:30", "2025-11-14 13:05", " 489.99"])
        self.assertEqual(record, {"flight_id": "BA2490", "origin": "LHR", "destination": "JFK",
                                  "departure_datetime": "2025-11-14 10:30",
                                  "arrival_datetime": "2025-11-14 13:05", "price": 489.99})
        self.assertIsInstance(record["price"], float)

    def test_load_airports(self):
        load_airports = load_module("validator").load_airports
        path = self.tmp / "airports.txt"
        path.write_text("# comment\nRIX\n\n  HEL  \nOSL\n   \n", encoding="utf-8")
        self.assertEqual(load_airports(str(path)), {"RIX", "HEL", "OSL"})


# ---------------------------------------------------------------- C. Parsing a file

class C_ParsingAFile(TempDirTest):
    def run_sample(self, csv_path=DB_CSV):
        proc = run_cli(["-i", csv_path, "-a", AIRPORTS, "-o", self.tmp / "db.json"], self.tmp)
        self.assertCleanExit(proc, 0)
        return proc

    def test_database_matches_expected(self):
        self.run_sample()
        self.assertEqual(read_json(self.tmp / "db.json"), read_json(EXPECTED / "db.json"))

    def test_errors_log_matches_expected(self):
        self.run_sample()
        self.assertTrue((self.tmp / "errors.log").is_file(), "errors.log was not written next to the database")
        self.assertEqual(graded_log(self.tmp / "errors.log"), expected_lines("db_errors.txt"))

    def test_errors_log_line_format(self):
        self.run_sample()
        for line in (self.tmp / "errors.log").read_text(encoding="utf-8").splitlines():
            if line.strip():
                with self.subTest(line=line):
                    self.assertRegex(line, LOG_LINE_RE, "log lines must start 'YYYY-MM-DD HH:MM:SS LEVEL '")

    def test_default_output_location(self):
        proc = run_cli(["-i", DB_CSV, "-a", AIRPORTS], self.tmp)
        self.assertCleanExit(proc, 0)
        self.assertTrue((self.tmp / "db.json").is_file(), "without -o, db.json must go to the current directory")
        self.assertTrue((self.tmp / "errors.log").is_file(), "errors.log must go next to db.json")

    def test_windows_line_endings(self):
        crlf = self.tmp / "db.csv"
        crlf.write_bytes(DB_CSV.read_bytes().replace(b"\r\n", b"\n").replace(b"\n", b"\r\n"))
        self.run_sample(crlf)
        self.assertEqual(read_json(self.tmp / "db.json"), read_json(EXPECTED / "db.json"))
        self.assertEqual(graded_log(self.tmp / "errors.log"), expected_lines("db_errors.txt"))

    def test_parse_files_function(self):
        parse_files = load_module("csv_loader").parse_files
        records, errors = parse_files([str(DB_CSV)], set(AIRPORT_SET))
        self.assertEqual(records, read_json(EXPECTED / "db.json"))
        self.assertEqual([graded_message(e) for e in errors], expected_lines("db_errors.txt"))
        for e in errors:
            self.assertFalse(e.endswith("\n"), "error messages must not end with a newline")

    def test_main_twice_in_one_process(self):
        main = load_module("flight_parser").main
        logger = logging.getLogger("flight_parser")
        for run in ("first", "second"):
            out = self.tmp / run
            out.mkdir()
            with contextlib.redirect_stdout(io.StringIO()):
                code = main(["-i", str(DB_CSV), "-a", str(AIRPORTS), "-o", str(out / "db.json")])
            with self.subTest(run=run):
                self.assertEqual(code, 0)
                self.assertEqual(graded_log(out / "errors.log"), expected_lines("db_errors.txt"),
                                 "duplicate or missing lines: is the handler removed at the end of main()?")
                self.assertEqual(logger.handlers, [], "main() must remove its logging handler before returning")


