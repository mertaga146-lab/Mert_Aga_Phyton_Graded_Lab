class D_CliAndFolders(TempDirTest):
    def test_folder_mode(self):
        proc = run_cli(["-d", FLIGHTS, "-a", AIRPORTS, "-o", self.tmp / "db.json"], self.tmp)
        self.assertCleanExit(proc, 0)
        self.assertEqual(read_json(self.tmp / "db.json"), read_json(EXPECTED / "flights_db.json"))
        self.assertEqual(graded_log(self.tmp / "errors.log"), expected_lines("flights_errors.txt"))

    def test_runtime_errors_exit_1(self):
        empty = self.tmp / "empty"
        empty.mkdir()
        bad_json = self.tmp / "bad.json"
        bad_json.write_text("[{not json", encoding="utf-8")
        not_array = self.tmp / "object.json"
        not_array.write_text('{"flight_id": "BA2490"}', encoding="utf-8")
        cases = {
            "missing CSV file": ["-i", self.tmp / "nope.csv", "-a", AIRPORTS],
            "missing folder": ["-d", self.tmp / "nope", "-a", AIRPORTS],
            "folder without .csv files": ["-d", empty, "-a", AIRPORTS],
            "missing JSON database": ["-j", self.tmp / "nope.json"],
            "database is not valid JSON": ["-j", bad_json],
            "database is not an array": ["-j", not_array],
            "query file is not valid JSON": ["-j", EXPECTED / "db.json", "-q", bad_json, "-r", self.tmp],
        }
        for name, args in cases.items():
            with self.subTest(case=name):
                proc = run_cli(args, self.tmp)
                self.assertCleanExit(proc, 1)
                self.assertTrue(any(l.startswith("Error:") for l in proc.stderr.splitlines()),
                                "print a line starting with 'Error:' to stderr")

    def test_usage_errors_exit_2(self):
        cases = {
            "no data source": [],
            "two data sources": ["-i", DB_CSV, "-j", EXPECTED / "db.json", "-a", AIRPORTS],
            "-i without -a": ["-i", DB_CSV],
            "-d without -a": ["-d", FLIGHTS],
            "-o with -j": ["-j", EXPECTED / "db.json", "-o", self.tmp / "x.json"],
            "unknown argument": ["-i", DB_CSV, "-a", AIRPORTS, "--colour", "red"],
        }
        for name, args in cases.items():
            with self.subTest(case=name):
                self.assertCleanExit(run_cli(args, self.tmp), 2)


# ---------------------------------------------------------------- E. Duplicates

class E_Duplicates(TempDirTest):
    HEADER = "flight_id,origin,destination,departure_datetime,arrival_datetime,price\n"

    def test_duplicates_in_one_file(self):
        csv_path = self.tmp / "dups.csv"
        csv_path.write_text(self.HEADER +
            "AB100,RIX,HEL,2025-11-20 08:00,2025-11-20 09:00,-5\n"      # invalid: does not count
            "AB100,RIX,HEL,2025-11-20 08:00,2025-11-20 09:00,50\n"      # valid
            "AB100,RIX,HEL,2025-11-20 08:00,2025-11-20 09:30,60\n"      # duplicate
            "AB100,RIX,HEL,2025-11-21 08:00,2025-11-21 09:00,50\n",     # other day: valid
            encoding="utf-8")
        parse_files = load_module("csv_loader").parse_files
        records, errors = parse_files([str(csv_path)], set(AIRPORT_SET))
        self.assertEqual([r["price"] for r in records], [50.0, 50.0])
        self.assertEqual([graded_message(e) for e in errors],
                         ["dups.csv:2: NON_POSITIVE_PRICE", "dups.csv:4: DUPLICATE_FLIGHT"])

    def test_duplicates_across_files(self):
        parse_files = load_module("csv_loader").parse_files
        paths = [str(FLIGHTS / n) for n in ("a_riga.csv", "b_oslo.csv")]
        records, errors = parse_files(paths, set(AIRPORT_SET))
        self.assertIn("b_oslo.csv:5: DUPLICATE_FLIGHT", [graded_message(e) for e in errors])
        self.assertEqual(ids(records), ids(read_json(EXPECTED / "flights_db.json")))


