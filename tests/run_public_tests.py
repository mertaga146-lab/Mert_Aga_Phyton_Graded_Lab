# ---------------------------------------------------------------- runner

class TallyResult(unittest.TextTestResult):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.passed = []

    def addSuccess(self, test):
        super().addSuccess(test)
        self.passed.append(test)


def main():
    os.chdir(ROOT)
    suite = unittest.defaultTestLoader.loadTestsFromModule(sys.modules[__name__])
    totals, passed = {}, {}
    for test in suite_tests(suite):
        group = type(test).__name__
        totals[group] = totals.get(group, 0) + 1

    runner = unittest.TextTestRunner(verbosity=2, resultclass=TallyResult)
    result = runner.run(suite)

    for test in result.passed:
        group = type(test).__name__
        passed[group] = passed.get(group, 0) + 1
    labels = {
        "A_Structure": "A. Structure", "B_RowValidation": "B. Row validation",
        "C_ParsingAFile": "C. Parsing a file", "D_CliAndFolders": "D. CLI and folders",
        "E_Duplicates": "E. Duplicates", "F_BasicQueries": "F. Basic queries",
        "G_ExtendedQueries": "G. Extended queries", "H_ResponseFile": "H. Response file",
    }
    print("\nSummary by grading group")
    for group in sorted(totals):
        print(f"  {labels.get(group, group):<24} {passed.get(group, 0)}/{totals[group]} tests passed")
    print("\nReminder: the final grade uses a larger hidden test set with different data.")
    return 0 if result.wasSuccessful() else 1


def suite_tests(suite):
    for item in suite:
        if isinstance(item, unittest.TestSuite):
            yield from suite_tests(item)
        else:
            yield item


if __name__ == "__main__":
    sys.exit(main())
