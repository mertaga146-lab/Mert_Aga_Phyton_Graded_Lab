class F_BasicQueries(TempDirTest):
    def write_queries(self, queries):
        path = self.tmp / "q.json"
        path.write_text(json.dumps(queries), encoding="utf-8")
        return path

    def response(self):
        files = list((self.tmp / "out").glob("response_*.json"))
        self.assertEqual(len(files), 1, "expected exactly one response file")
        return read_json(files[0])

    def run_queries_cli(self, queries, source=("-j", EXPECTED / "db.json")):
        (self.tmp / "out").mkdir()
        proc = run_cli([*source, "-q", self.write_queries(queries), "-r", self.tmp / "out"], self.tmp)
        self.assertCleanExit(proc, 0)
        return self.response()

    def test_exact_match_and_filters(self):
        queries = [
            {"origin": "LHR", "destination": "JFK"},
            {"price": 200.00},
            {"departure_datetime": "2025-11-15 00:00", "arrival_datetime": "2025-11-16 00:00"},
            {"destination": "RIX"},
            {"arrival_datetime": "2025-11-14 13:05"},
            {"departure_datetime": "2025-11-20 21:10"},
            {"flight_id": "ba2490"},
            {},
        ]
        expected = [
            ["BA2490"],
            ["LH172", "FR1234", "BT102", "DY4501"],
            ["FR1234"],
            ["LH172"],
            ["BA2490", "LH172", "BT102"],
            ["DY4501", "AF112"],
            [],
            ["BA2490", "LH172", "FR1234", "BT102", "AA9999", "DY4501", "AF112"],
        ]
        result = self.run_queries_cli(queries)
        self.assertEqual(len(result), len(queries))
        for q, entry, exp in zip(queries, result, expected):
            with self.subTest(query=q):
                self.assertEqual(entry["query"], q)
                self.assertEqual(ids(entry["matches"]), exp)
                self.assertNotIn("error", entry)

    def test_single_query_object(self):
        result = self.run_queries_cli({"origin": "RIX"})
        self.assertIsInstance(result, list)
        self.assertEqual(len(result), 1)
        self.assertEqual(ids(result[0]["matches"]), ["FR1234", "BT102"])

    def test_parse_and_query_in_one_run(self):
        result = self.run_queries_cli([{"origin": "LHR"}], source=("-i", DB_CSV, "-a", AIRPORTS, "-o", self.tmp / "db.json"))
        self.assertEqual(result[0]["matches"], [read_json(EXPECTED / "db.json")[0]])

    def test_run_query_function(self):
        run_query = load_module("query").run_query
        db = read_json(EXPECTED / "db.json")
        entry = run_query(db, {"origin": "OSL"})
        self.assertEqual(entry, {"query": {"origin": "OSL"}, "matches": [db[5]]})


